线性方程最迷人的地方是**叠加原理**：两个解相加还是解，解乘常数还是解。于是全部解的集合是一个向量空间。问题立刻变成线性代数式的三个追问：这个空间有几维？怎样找一组基？非齐次项来了怎么办？

